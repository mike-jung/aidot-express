/**
 * chartPalette — 차트 색을 한 곳에서. (v1.10.44)
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  왜 바꿨는가
 * ══════════════════════════════════════════════════════════════════════════
 *  예전에는 부트스트랩 기본색(`#dc3545` `#198754` `#0d6efd` …)을 화면마다
 *  직접 적었습니다. 두 가지가 문제였습니다.
 *
 *   ① **빨강과 초록이 같은 화면에** 있었습니다. 적록색약(가장 흔한 색각
 *      이상)에게는 두 선이 거의 같은 색으로 보입니다.
 *   ② 버튼·배지에 쓰라고 만든 색이라 **채도가 높습니다.** 선이 여러 개
 *      겹치면 눈이 아프고, 무엇이 중요한지 구분되지 않습니다.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  무엇을 골랐는가
 * ══════════════════════════════════════════════════════════════════════════
 *  IBM Carbon 의 데이터 시각화 팔레트를 바탕으로 했습니다 —
 *  **색각 이상을 고려해 만들어졌고**, 순서대로 써도 인접한 두 색이
 *  구분되도록 설계돼 있습니다.
 *
 *  ⚠ 색만으로 구분하지 않습니다. 두 번째 계열은 **점선**으로도 갈립니다
 *    (W3C: 색이 정보를 전달하는 유일한 수단이면 안 된다).
 */

/** 계열 색 — 인접한 둘이 확실히 갈리는 순서 */
export const SERIES = Object.freeze({
  blue:   '#4589ff',   // 기본 — 가장 많이 쓰는 값
  teal:   '#08bdba',   // 두 번째 계열 (파랑과 명도 차이가 크다)
  purple: '#a56eff',
  amber:  '#d2a106',   // 주의 — 주황 대신. 빨강과 덜 헷갈린다
  magenta:'#ee5396',
  cyan:   '#1192e8',
});

/** 상태 색 — 값이 아니라 **판정**을 나타낼 때만 */
export const STATE = Object.freeze({
  warn:   '#d2a106',   // 경고선
  danger: '#da1e28',   // 위험선
  muted:  '#8d8d8d',   // 축·눈금
  grid:   '#e8e8e8',   // 격자
});

/**
 * 화면별 색 짝. **한 화면 안에서 빨강+초록이 함께 오지 않게** 짰습니다.
 *
 *  ⚠ 여기서 고르는 것은 '값의 종류' 이지 '좋고 나쁨' 이 아닙니다.
 *    좋고 나쁨은 STATE(경고선·위험선)가 나타냅니다.
 */
export const PAIRS = Object.freeze({
  os:     { a: SERIES.blue,   b: SERIES.teal },     // CPU / Memory
  http:   { a: SERIES.teal,   b: SERIES.amber },    // RPS / 평균 응답
  db:     { a: SERIES.purple, b: SERIES.cyan },     // QPS / 평균 쿼리
  memory: { a: SERIES.cyan,   b: SERIES.magenta },  // RSS / Heap
});

export default { SERIES, STATE, PAIRS };
